import json
import os

import psycopg
from dotenv import load_dotenv

load_dotenv()

OUTPUT_PATH = "tests/fixtures/ci_eval_seed.sql"

# Deterministic coverage for the 7 DB tool tests in tests/test_agent_tools.py.
# Each pick is (label, WHERE predicate, count). Keys are unioned and re-fetched
# once, so the emitted SQL is byte-stable while the frozen snapshot is unchanged.
# Every pick INNER JOINs posting_embeddings: a role without an embedding is
# invisible to vector_search, and 3 empty-text roles in the corpus have none.
PICKS: list[tuple[str, str, int]] = [
    ("staff+ seniority", "s.seniority = 'staff+'", 2),
    (
        "senior USD salary",
        "s.seniority = 'senior' AND s.salary_currency = 'USD' AND s.salary_max IS NOT NULL",
        2,
    ),
    ("RUB salary", "s.salary_currency = 'RUB' AND s.salary_max IS NOT NULL", 1),
    (
        "null-currency salary",
        "s.salary_currency IS NULL AND s.salary_max IS NOT NULL",
        1,
    ),
    ("web3 role", "r.source = 'web3'", 1),
    ("remotive role", "r.source = 'remotive'", 1),
]


def assert_eval(conn: psycopg.Connection) -> None:
    with conn.cursor() as cur:
        cur.execute("SELECT role FROM db_meta")
        row = cur.fetchone()
    if row is None or row[0] != "eval":
        raise RuntimeError(
            f"db_meta.role is {row and row[0]!r}, not 'eval' — refusing to export a fixture "
            "from a database that is not the frozen snapshot."
        )


def lit(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def arr_lit(values: list[str] | None) -> str:
    if not values:
        return "ARRAY[]::text[]"
    return "ARRAY[" + ", ".join(lit(v) for v in values) + "]::text[]"


def jsonb_lit(value: dict[str, str] | None) -> str:
    if not value:
        return "'{}'::jsonb"
    return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def pick_keys(cur: psycopg.Cursor, where: str, n: int) -> list[tuple[int, int]]:
    cur.execute(
        f"""
        SELECT s.raw_posting_id, s.role_index
        FROM structured_postings s
        JOIN raw_postings r ON r.id = s.raw_posting_id
        JOIN posting_embeddings e USING (raw_posting_id, role_index)
        WHERE {where}
        ORDER BY s.raw_posting_id, s.role_index
        LIMIT %s
        """,
        (n,),
    )
    return [(row[0], row[1]) for row in cur.fetchall()]


def build(conn: psycopg.Connection) -> str:
    assert_eval(conn)

    with conn.cursor() as cur:
        keys: list[tuple[int, int]] = []
        seen: set[tuple[int, int]] = set()
        for _label, where, n in PICKS:
            for key in pick_keys(cur, where, n):
                if key not in seen:
                    seen.add(key)
                    keys.append(key)
        keys.sort()
        if not keys:
            raise RuntimeError("fixture picks resolved to zero roles — snapshot is empty?")

        ids = sorted({key[0] for key in keys})
        key_set = set(keys)

        cur.execute(
            "SELECT id, source, external_id, raw_text, thread_month, posted_at "
            "FROM raw_postings WHERE id = ANY(%s) ORDER BY id",
            (ids,),
        )
        raw_rows = cur.fetchall()

        cur.execute(
            "SELECT id, raw_posting_id, role_index, company, title, location, seniority, "
            "remote_policy, employment_type, stack, salary_min, salary_max, salary_currency, "
            "source_quotes, description, derived_fields "
            "FROM structured_postings WHERE raw_posting_id = ANY(%s) "
            "ORDER BY raw_posting_id, role_index",
            (ids,),
        )
        sp_rows = [r for r in cur.fetchall() if (r[1], r[2]) in key_set]

        cur.execute(
            "SELECT raw_posting_id, role_index, embedding, embedded_text "
            "FROM posting_embeddings WHERE raw_posting_id = ANY(%s) "
            "ORDER BY raw_posting_id, role_index",
            (ids,),
        )
        pe_rows = [r for r in cur.fetchall() if (r[0], r[1]) in key_set]

    lines: list[str] = [
        "-- ci_eval_seed.sql — curated subset of the frozen eval corpus (jobmarket_eval).",
        "-- Generated by evals/export_ci_fixture.py; real rows only, never invented.",
        "-- Schema lives in db/schema/*.sql — this file is data-only, applied after it.",
        "",
        "BEGIN;",
        "",
        "-- The schema's 003 seeds db_meta.role='live'; the tool tests assert 'eval'.",
        "UPDATE db_meta SET role = 'eval';",
        "",
        "INSERT INTO raw_postings (id, source, external_id, raw_text, thread_month, posted_at)",
        "OVERRIDING SYSTEM VALUE VALUES",
    ]
    for i, row in enumerate(raw_rows):
        rid, source, external_id, raw_text, thread_month, posted_at = row
        suffix = "," if i < len(raw_rows) - 1 else ";"
        thread = lit(thread_month.isoformat()) if thread_month is not None else "NULL"
        posted = lit(posted_at.isoformat()) if posted_at is not None else "NULL"
        lines.append(
            f"  ({rid}, {lit(source)}, {lit(external_id)}, {lit(raw_text)}, "
            f"{thread}, {posted}){suffix}"
        )

    lines += [
        "",
        "INSERT INTO structured_postings (id, raw_posting_id, role_index, company, title,",
        "  location, seniority, remote_policy, employment_type, stack, salary_min, salary_max,",
        "  salary_currency, source_quotes, description, derived_fields)",
        "OVERRIDING SYSTEM VALUE VALUES",
    ]
    for i, row in enumerate(sp_rows):
        (
            sid,
            rid,
            ridx,
            company,
            title,
            location,
            seniority,
            remote_policy,
            employment_type,
            stack,
            salary_min,
            salary_max,
            salary_currency,
            source_quotes,
            description,
            derived_fields,
        ) = row
        suffix = "," if i < len(sp_rows) - 1 else ";"
        s_min = "NULL" if salary_min is None else str(salary_min)
        s_max = "NULL" if salary_max is None else str(salary_max)
        lines.append(
            f"  ({sid}, {rid}, {ridx}, {lit(company)}, {lit(title)}, {lit(location)}, "
            f"{lit(seniority)}, {lit(remote_policy)}, {lit(employment_type)}, "
            f"{arr_lit(stack)}, {s_min}, {s_max}, "
            f"{lit(salary_currency)}, {jsonb_lit(source_quotes)}, {lit(description)}, "
            f"{arr_lit(derived_fields)}){suffix}"
        )

    lines += [
        "",
        "INSERT INTO posting_embeddings (raw_posting_id, role_index, embedding, embedded_text)",
        "VALUES",
    ]
    for i, row in enumerate(pe_rows):
        rid, ridx, embedding, embedded_text = row
        suffix = "," if i < len(pe_rows) - 1 else ";"
        # embedding arrives as the vector's text form '[...]' — re-cast on insert.
        lines.append(f"  ({rid}, {ridx}, {lit(embedding)}::vector, {lit(embedded_text)}){suffix}")

    lines += [
        "",
        "-- Explicit ids were inserted, so the identity sequences must advance past them",
        "-- or a future default-value insert collides. Tests are read-only; this is hygiene.",
        (
            "SELECT setval(pg_get_serial_sequence('raw_postings', 'id'), "
            "(SELECT max(id) FROM raw_postings));"
        ),
        (
            "SELECT setval(pg_get_serial_sequence('structured_postings', 'id'), "
            "(SELECT max(id) FROM structured_postings));"
        ),
        "",
        "COMMIT;",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    with psycopg.connect(os.environ["EVAL_DATABASE_URL"]) as conn:
        sql = build(conn)

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(sql)

    print(f"Wrote {OUTPUT_PATH} ({len(sql)} bytes, {len(sql.splitlines())} lines)")
